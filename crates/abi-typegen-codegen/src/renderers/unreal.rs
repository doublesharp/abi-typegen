    #[test]
    fn type_paths_preserve_field_and_array_ancestry() {
        let ir = parse_artifact("C", r#"{"abi":[{"type":"function","name":"f","stateMutability":"view","inputs":[{"name":"x","type":"tuple[]","components":[{"name":"v","type":"uint256"}]},{"name":"xItem","type":"tuple","components":[{"name":"v","type":"uint256"}]},{"name":"a","type":"tuple","components":[{"name":"b","type":"tuple","components":[{"name":"v","type":"uint256"}]}]},{"name":"ab","type":"tuple","components":[{"name":"v","type":"uint256"}]}],"outputs":[]}]}"#).expect("fixture");
        let output = render_unreal_artifacts(&ir, true, "HOST_API");
        for name in [
            "FCF_Input_X_Item",
            "FCF_Input_XItem",
            "FCF_Input_A_B",
            "FCF_Input_Ab",
        ] {
            assert_eq!(
                output
                    .header
                    .matches(&format!("struct HOST_API {name}\n"))
                    .count(),
                1,
                "{name}"
            );
        }
        let names = declared_symbol_names(&ir, true);
        let unique = names
            .iter()
            .map(|n| n.to_lowercase())
            .collect::<HashSet<_>>();
        assert_eq!(names.len(), unique.len());
    }

