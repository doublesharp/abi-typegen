//! Thin Unreal Engine adapters over abi-typegen's generated C API.
//!
//! The Unreal backend does not implement ABI encoding, hashing, RPC signing, or
//! cryptography. It emits typed ABI DTOs and asynchronous read/event nodes that
//! call the generated C encode/decode functions, which in turn use the shared
//! Rust ABI runtime. Named tuple DTOs and array wrappers expose the complete ABI
//! through typed codecs, including indexed event hashes. Signing remains app-owned.

